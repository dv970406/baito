export const MESSAGES: Record<CaptionLang, Record<MessageKey, string>> = { ko, en };

export type MessageVars = Record<string, string | number>;

/** "{name} 시프트" + { name: "아침" } → "아침 시프트". vars 에 없는 자리표시는 그대로 둔다 */
export function format(message: string, vars?: MessageVars): string {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

/** 훅 밖(공유 문구·PNG 렌더러 등)에서 쓰는 번역 함수 */
export function translate(lang: CaptionLang, key: MessageKey, vars?: MessageVars): string {
  return format(MESSAGES[lang][key] ?? ko[key], vars);
}

export type TFunction = (key: MessageKey, vars?: MessageVars) => string;
